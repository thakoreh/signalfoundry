import { chromium } from '<LOCAL_HOME>/microsaas-projects/signalfoundry-rc-review/frontend/node_modules/playwright-core/index.mjs';
import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
const root='<HISTORICAL_LOCAL_ARTIFACT_ROOT>/final-frontend-review';
const fixture=JSON.parse(await fs.readFile(root+'/fixture.json','utf8'));
const width=Number(process.env.REVIEW_WIDTH||1440);
const browser=await chromium.launch({channel:'chrome',headless:true});
const context=await browser.newContext({viewport:{width,height:900}});
const page=await context.newPage();
const requests=[]; const errors=[]; const responses=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>{ const u=new URL(r.url()); if(u.hostname==='127.0.0.1'&&Number(u.port)===3063) requests.push({method:r.method(),path:u.pathname+u.search,body:r.postData()}); else requests.push({method:r.method(),path:r.url(),external:true}); });
page.on('response',r=>{ if(r.url().includes('/next-up')) responses.push({status:r.status(),url:r.url()}); });
await page.route('**/*',route=>{const u=new URL(route.request().url()); return (u.hostname==='127.0.0.1'&&Number(u.port)===3063)?route.continue():route.abort();});
const shot=async n=>{await page.screenshot({path:`${root}/${n}-${width}.png`,fullPage:true}); await page.screenshot({path:`${root}/${n}-viewport-${width}.png`,fullPage:false});};
const metrics=async()=>await page.evaluate(()=>{const vw=document.documentElement.clientWidth; const offenders=[...document.querySelectorAll('body *')].map(el=>{const r=el.getBoundingClientRect();return {tag:el.tagName,text:(el.textContent||'').trim().replace(/\s+/g,' ').slice(0,100),left:Math.round(r.left),right:Math.round(r.right),width:Math.round(r.width),height:Math.round(r.height)}}).filter(x=>x.width>0&&x.height>0&&(x.left<-1||x.right>vw+1));return {vw,scrollWidth:document.documentElement.scrollWidth,offenders:offenders.slice(0,12)}});
try {
  await page.goto('http://127.0.0.1:3063/workspace',{waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'Next up',exact:true}).waitFor({timeout:10000});
  await page.getByText('Fictional Business Property Management',{exact:true}).waitFor({timeout:10000});
  await page.waitForTimeout(300);
  const workspaceText=await page.locator('body').innerText();
  const nextLink=page.getByRole('link',{name:'Open conversation',exact:true});
  assert.equal(await nextLink.count(),1);
  const href=await nextLink.getAttribute('href');
  assert.equal(href,`/workspace/outreach/${fixture.search_id}?thread=${fixture.thread_id}`);
  const preNav=await metrics(); await shot('returning-next-up');
  const beforePosts=requests.filter(r=>r.method==='POST');
  await nextLink.click();
  await page.waitForURL(`**/workspace/outreach/${fixture.search_id}?thread=${fixture.thread_id}`);
  await page.getByRole('button',{name:'Pause this outreach',exact:true}).waitFor();
  await page.waitForTimeout(300);
  const threadText=await page.locator('body').innerText();
  assert.match(threadText,/hello@business.com/);
  assert.match(threadText,/Interested/);
  assert.equal(await page.locator('textarea').count() > 0, true);
  const afterOpenPosts=requests.filter(r=>r.method==='POST');
  assert.deepEqual(afterOpenPosts,beforePosts);
  await page.reload({waitUntil:'domcontentloaded'});
  await page.getByRole('button',{name:'Pause this outreach',exact:true}).waitFor();
  assert.equal((await page.locator('body').innerText()).includes('hello@business.com'),true);
  assert.deepEqual(requests.filter(r=>r.method==='POST'),beforePosts);
  await page.goBack({waitUntil:'domcontentloaded'});
  await page.getByRole('heading',{name:'Next up',exact:true}).waitFor();
  assert.equal(await page.getByRole('link',{name:'Open conversation',exact:true}).count(),1);
  const afterBackPosts=requests.filter(r=>r.method==='POST');
  assert.deepEqual(afterBackPosts,beforePosts);
  const threadMetrics=await metrics(); await shot('returning-open-thread');
  console.log(JSON.stringify({verdict:'PASS',width,browser:await browser.version(),search_id:fixture.search_id,thread_id:fixture.thread_id,href,workspaceHasNextUp:workspaceText.includes('Next up'),nextUpResponses:responses,postsBeforeOpen:beforePosts,postsAfterOpen:afterBackPosts,preNav,threadMetrics,pageErrors:errors,requestPaths:requests.filter(r=>!r.external).map(r=>`${r.method} ${r.path}`)}));
} catch (e) { await shot('returning-failure').catch(()=>{}); console.log(JSON.stringify({verdict:'FAIL',width,error:e.message,stack:e.stack,body:(await page.locator('body').innerText().catch(()=>'' )).slice(0,4000),requests,errors,metrics:await metrics().catch(()=>null)})); process.exitCode=1; }
finally { await context.close(); await browser.close(); }
